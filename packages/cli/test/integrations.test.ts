import { describe, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SKILL_MD } from '@conus/protocol';
import { hookTotalBudgetMs } from '../src/hook/run';

const root = join(dirname(fileURLToPath(import.meta.url)), '../../..');
const read = (p: string) => readFileSync(join(root, p), 'utf8');

describe('Claude Code plugin', () => {
  it('manifest and marketplace are valid and point at each other', () => {
    expect(JSON.parse(read('integrations/claude-code/.claude-plugin/plugin.json')).name).toBe('conus');
    const m = JSON.parse(read('.claude-plugin/marketplace.json'));
    expect(m.plugins[0]).toMatchObject({ name: 'conus', source: './integrations/claude-code' });
  });
  it('MCP config starts the bundled bridge with node (no PATH or .cmd shim needed), and the bundle is current', () => {
    const conus = JSON.parse(read('integrations/claude-code/.mcp.json')).mcpServers.conus;
    expect(conus).toEqual({ command: 'node', args: ['${CLAUDE_PLUGIN_ROOT}/mcp/conus-mcp.mjs'], alwaysLoad: true });
    expect(read('integrations/claude-code/mcp/conus-mcp.mjs')).toContain('Generated by `npm run gen`');
  });
  it('hooks cover all five events with conus hook commands', () => {
    const h = JSON.parse(read('integrations/claude-code/hooks/hooks.json')).hooks;
    expect(Object.keys(h).sort()).toEqual(['PostToolUse', 'SessionEnd', 'SessionStart', 'Stop', 'UserPromptSubmit']);
    for (const groups of Object.values<any[]>(h)) for (const g of groups) for (const x of g.hooks) expect(x.command).toMatch(/^conus hook (session-start|prompt|tool|stop|session-end) --agent claude$/);
    // PowerShell: Claude Code's shell tool on Windows (CLAUDE_CODE_USE_POWERSHELL_TOOL=1)
    expect(h.PostToolUse[0].matcher).toBe('Edit|Write|MultiEdit|NotebookEdit|Bash|PowerShell|mcp__.*');
  });
  it('every hook timeout covers the whole budget of the hook plus a second for process start (Stop: 1 s pre-work + the full 5 s request)', () => {
    const h = JSON.parse(read('integrations/claude-code/hooks/hooks.json')).hooks;
    const events = { SessionStart: 'session-start', UserPromptSubmit: 'prompt', PostToolUse: 'tool', Stop: 'stop', SessionEnd: 'session-end' } as const;
    for (const [event, hook] of Object.entries(events)) expect(h[event][0].hooks[0].timeout * 1000, event).toBeGreaterThanOrEqual(hookTotalBudgetMs(hook) + 1000);
    expect(hookTotalBudgetMs('stop')).toBe(6000);
  });
  it('generated skill is in sync with the protocol package (run `npm run gen` if this fails)', () => {
    expect(read('integrations/claude-code/skills/task-protocol/SKILL.md')).toBe(SKILL_MD);
  });
});
