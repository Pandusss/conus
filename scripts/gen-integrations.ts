import { build } from 'esbuild';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SKILL_MD } from '../packages/protocol/src';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const plugin = join(root, 'integrations/claude-code');

const skill = join(plugin, 'skills/task-protocol/SKILL.md');
mkdirSync(dirname(skill), { recursive: true });
writeFileSync(skill, SKILL_MD);
console.log('wrote', skill);

// The plugin runs its MCP bridge with `node`, so the bundle is committed with the plugin.
const bridge = join(plugin, 'mcp/conus-mcp.mjs');
await build({
  entryPoints: [join(root, 'packages/cli/src/mcp-entry.ts')], bundle: true, platform: 'node', target: 'node22', format: 'esm',
  outfile: bridge, legalComments: 'none',
  banner: { js: '// Generated by `npm run gen` from packages/cli/src/mcp-entry.ts. Do not edit.' },
});
console.log('wrote', bridge);
