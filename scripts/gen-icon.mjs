// Draws the Conus mark: elementary cellular automaton Rule 30 grown from a single cell.
// The cone snail Conus textile paints its shell with the same kind of rule, one growth line at a time;
// the pattern it grows from one cell is a cone. Run `node scripts/gen-icon.mjs` after changing anything here.
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const INDIGO = '#4f46e5';

/** Rows of Rule 30 from one live cell; each row is 2·rows−1 cells wide. */
export function rule30(rows) {
  const n = 2 * rows - 1;
  let row = Array.from({ length: n }, (_, i) => i === rows - 1);
  const out = [];
  for (let r = 0; r < rows; r++) {
    out.push(row);
    row = row.map((_, i) => (i > 0 && row[i - 1]) !== (row[i] || (i < n - 1 && row[i + 1])));
  }
  return out;
}

/** The cone as cells inside a 64×64 box: widest row on top, the seed cell at the bottom. */
function cellBoxes(rows, { top, bottom, width }) {
  const grid = rule30(rows);
  const n = 2 * rows - 1;
  const cw = width / n;
  const ch = (bottom - top) / rows;
  const gap = Math.min(cw, ch) * 0.24;
  const x0 = 32 - width / 2;
  const boxes = [];
  grid.forEach((row, r) => row.forEach((on, c) => {
    if (!on) return;
    // grid row 0 is the seed; it is drawn last, at the bottom
    const y = bottom - (r + 1) * ch;
    const x = x0 + (n - 1 - c) * cw;
    boxes.push([x + gap / 2, y + gap / 2, cw - gap, ch - gap, gap * 0.9].map((v) => Number(v.toFixed(2))));
  }));
  return boxes;
}

const cells = (rows, box) =>
  cellBoxes(rows, box).map(([x, y, w, h, rx]) => `<rect x="${x}" y="${y}" width="${w}" height="${h}" rx="${rx}"/>`).join('');

function mark({ rows, top, bottom, width, background = true }) {
  const bg = background ? `<rect width="64" height="64" rx="15" fill="${INDIGO}"/>` : '';
  const fill = background ? '#fff' : INDIGO;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">${bg}<g fill="${fill}">${cells(rows, { top, bottom, width })}</g></svg>\n`;
}

/** The repository's social preview (1280×640). Render the PNG with: rsvg-convert docs/assets/social.svg -o docs/assets/social.png */
function social() {
  const font = `font-family="Inter, 'Noto Sans', 'DejaVu Sans', sans-serif"`;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="1280" height="640" viewBox="0 0 1280 640">
<rect width="1280" height="640" fill="#0e0e11"/>
<g transform="translate(96 192) scale(4)">${mark(full).replace(/^<svg[^>]*>|<\/svg>\n$/g, '')}</g>
<text x="412" y="322" ${font} font-size="120" font-weight="700" fill="#ececf1" letter-spacing="-3">Conus</text>
<text x="418" y="386" ${font} font-size="34" fill="#c4c4cc">A task manager your AI agents keep themselves</text>
<text x="418" y="438" ${font} font-size="24" fill="#9494a0">Claude Code · Codex · Gemini CLI · MCP · self-hosted · MIT</text>
</svg>
`;
}

// Large sizes show the full pattern; small ones keep fewer, bigger cells so the cone survives at 16 px.
const full = { rows: 11, top: 13, bottom: 52, width: 44 };
const small = { rows: 6, top: 12, bottom: 53, width: 46 };

const write = (rel, text) => {
  const file = join(root, rel);
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, text);
  console.log('wrote', rel);
};

write('docs/assets/conus.svg', mark(full));
write('docs/assets/social.svg', social());
write('packages/ui/public/favicon.svg', mark(small));
write('packages/ui/src/brand-cells.ts',
  `// Generated by scripts/gen-icon.mjs: the cells of the small Conus mark in a 64×64 box, as [x, y, width, height, rx].\n` +
  `export const BRAND_CELLS: readonly (readonly [number, number, number, number, number])[] = ${JSON.stringify(cellBoxes(small.rows, small))};\n`);
